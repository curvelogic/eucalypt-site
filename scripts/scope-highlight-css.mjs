// Take the stylesheet of `cargo xtask highlight-html --css` and keep what
// the playground shares with it: the light and dark custom properties and
// the one rule per capture class. The renderer scopes those rules to
// `pre.eu`; the playground's editor is not a <pre>, so they are rescoped
// to `.eu`. Page rules (body, headings, the <pre> box) are dropped. Fails
// if the input does not have the shape this expects, so a change to the
// renderer's output is noticed rather than silently mis-scoped.
import { readFileSync, writeFileSync } from "node:fs";

const [input, output] = process.argv.slice(2);
if (!input || !output) {
  console.error("usage: scope-highlight-css.mjs IN.css OUT.css");
  process.exit(2);
}

const css = readFileSync(input, "utf8");
const kept = [];
let captureRules = 0;
let rootBlocks = 0;
// Top-level blocks: brace-balanced, so the @media block stays whole.
let depth = 0;
let start = 0;
for (let i = 0; i < css.length; i++) {
  if (css[i] === "{") depth++;
  else if (css[i] === "}" && --depth === 0) {
    const block = css.slice(start, i + 1).trim();
    start = i + 1;
    const selector = block.slice(0, block.indexOf("{")).trim();
    if (selector.startsWith(":root") || selector.startsWith("@media")) {
      kept.push(block);
      rootBlocks++;
    } else if (/^pre\.eu \.ts-[a-z-]+$/.test(selector)) {
      kept.push(block.replace(/^pre\.eu /, ".eu "));
      captureRules++;
    } else if (!["body", "h2.eu-file", "pre.eu"].includes(selector)) {
      console.error(`unexpected rule in the renderer's stylesheet: ${selector}`);
      process.exit(1);
    }
  }
}
if (depth !== 0 || rootBlocks < 2 || captureRules === 0) {
  console.error("the renderer's stylesheet does not have the expected shape");
  process.exit(1);
}
writeFileSync(
  output,
  "/* Generated by scripts/vendor-eucalypt.sh from `cargo xtask highlight-html --css`. Do not edit. */\n" +
    kept.join("\n") +
    "\n",
);
